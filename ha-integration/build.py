"""Bundle the self-contained HA editor, the native SVG icon set and the Kindle default frame."""
import json
from pathlib import Path
import shutil
import sys

ROOT = Path(__file__).parent
sys.path.insert(0, str(ROOT))
from kindle_model import load  # noqa: E402

SOURCES = ("util.js", "painter.js", "styles.js", "editor.js")
ICON_COLORS = {"": "#000", "-w": "#fff", "-g": "#b4b4b4"}

icons = json.loads((ROOT / "frontend/icons.json").read_text(encoding="utf-8"))
bundle = ["// Generated by ha-integration/build.py from frontend/src; edit the sources instead.",
          "const ICONS = " + json.dumps(icons, ensure_ascii=False) + ";"]
bundle += [(ROOT / "frontend/src" / name).read_text(encoding="utf-8") for name in SOURCES]
target = ROOT / "custom_components/kindle_panel/frontend/editor.js"
target.parent.mkdir(parents=True, exist_ok=True)
target.write_text("\n".join(bundle), encoding="utf-8", newline="\n")

native_icons = ROOT.parent / "native-ha/icons"
native_icons.mkdir(parents=True, exist_ok=True)
for stale in native_icons.glob("*.svg"):
    stale.unlink()
for name, body in icons.items():
    for suffix, color in ICON_COLORS.items():
        svg = ("<svg xmlns='http://www.w3.org/2000/svg' viewBox='0 0 24 24' fill='none' stroke='" + color
               + "' stroke-width='2' stroke-linecap='round' stroke-linejoin='round'>" + body + "</svg>")
        (native_icons / f"{name}{suffix}.svg").write_text(svg, encoding="utf-8", newline="\n")
print(f"Built HA editor ({len(SOURCES)} sources) and {len(icons)} native icons in {len(ICON_COLORS)} colors")

protocol, _, render = load()
frame, _ = render.snapshot(protocol.default_layout(), 0, {}, "°C", 758, 1024)
(ROOT.parent / "native-ha/default-snapshot.json").write_text(json.dumps(frame, ensure_ascii=False), encoding="utf-8", newline="\n")
shutil.copyfile(ROOT.parent / "native-ha/controller-source.lua", ROOT.parent / "native-ha/nativeha.koplugin/main.lua")
